// Converts public/art/*.svg into React components under components/art/.
// Run after: node scripts/generate-art.mjs && node scripts/svg-to-components.mjs
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const IN = join(process.cwd(), "public", "art");
const OUT = join(process.cwd(), "components", "art");
mkdirSync(OUT, { recursive: true });

const ATTR = [
  ["stroke-width", "strokeWidth"],
  ["stroke-linecap", "strokeLinecap"],
  ["stroke-linejoin", "strokeLinejoin"],
  ["fill-rule", "fillRule"],
  ["clip-rule", "clipRule"],
  ["clip-path", "clipPath"],
  ["stop-color", "stopColor"],
  ["stop-opacity", "stopOpacity"],
  ["xmlns", "xmlns"],
];

function toComponentName(file) {
  return file
    .replace(/\.svg$/, "")
    .split(/[-_]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

function toArtId(file) {
  return file.replace(/\.svg$/, "");
}

function toJsx(s) {
  for (const [from, to] of ATTR) {
    s = s.replaceAll(from, to);
  }
  return s;
}

function jsxAttrs(openTag) {
  let s = toJsx(openTag);
  s = s.replace(/\s(width|height)="[^"]*"/g, "");
  s = s.replace(/\srole="img"/g, "");
  return s;
}

function convert(svg) {
  const titleMatch = svg.match(/<title>([^<]*)<\/title>/);
  const title = titleMatch?.[1] ?? "";
  let body = svg.replace(/<\?xml[^>]*>/, "").trim();
  body = body.replace(/<title>[^<]*<\/title>/, "");
  const openEnd = body.indexOf(">");
  const open = body.slice(0, openEnd + 1);
  const close = "</svg>";
  const inner = body.slice(openEnd + 1, body.lastIndexOf(close));
  const openJsx = jsxAttrs(open.replace("<svg", "<svg"));
  return { title, openJsx, inner };
}

const files = readdirSync(IN).filter((f) => f.endsWith(".svg"));
const exports = [];

for (const file of files) {
  const id = toArtId(file);
  const name = toComponentName(file);
  const { title, openJsx, inner } = convert(readFileSync(join(IN, file), "utf8"));
  const innerJsx = toJsx(inner);
  const src = `import type { SVGProps } from "react";

export const artId = "${id}" as const;
export const artTitle = ${JSON.stringify(title)};

export function ${name}({ className, ...props }: SVGProps<SVGSVGElement>) {
  return (
    ${openJsx.replace("<svg", "<svg className={className} role=\"img\" {...props}")}
      ${innerJsx}
    </svg>
  );
}
`;
  writeFileSync(join(OUT, `${name}.tsx`), src);
  exports.push({ id, name });
}

const index = `/* Generated by scripts/svg-to-components.mjs — do not edit by hand. */
import type { ComponentType, SVGProps } from "react";
${exports.map((e) => `import { ${e.name}, artId as ${e.name}Id } from "./${e.name}";`).join("\n")}

export type ArtId =
${exports.map((e) => `  | "${e.id}"`).join("\n")};

const map: Record<ArtId, ComponentType<SVGProps<SVGSVGElement>>> = {
${exports.map((e) => `  "${e.id}": ${e.name},`).join("\n")}
};

export function ArtIllustration({
  id,
  alt,
  className,
  ...props
}: { id: ArtId; alt: string; className?: string } & SVGProps<SVGSVGElement>) {
  const C = map[id];
  return <C className={className} aria-label={alt} {...props} />;
}
`;

writeFileSync(join(OUT, "index.tsx"), index);
console.log(`Wrote ${files.length} art components.`);
